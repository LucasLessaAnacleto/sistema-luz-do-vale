CREATE TABLE permissao_tipo_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfil_id BIGINT NOT NULL,
    tipo_documento_id BIGINT NOT NULL,

    CONSTRAINT fk_permissao_tipo_documento_perfil FOREIGN KEY (perfil_id) REFERENCES perfil(id),
    CONSTRAINT fk_permissao_tipo_documento_tipo_documento FOREIGN KEY (tipo_documento_id) REFERENCES tipo_documento(id)
);