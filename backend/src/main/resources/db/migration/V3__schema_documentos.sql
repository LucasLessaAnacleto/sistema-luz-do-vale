CREATE TABLE tipo_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    descricao TEXT NOT NULL,
    exige_assinatura BOOLEAN,
    ativo BOOLEAN,
    dt_desativado TIMESTAMP
);

CREATE TABLE tipo_documento_versao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento_id BIGINT NOT NULL,
    versao INT,
    campos JSONB,
    dt_criacao TIMESTAMP,

    CONSTRAINT fk_tipo_documento_versao_tipo_documento FOREIGN KEY (tipo_documento_id) REFERENCES tipo_documento(id)
);

CREATE TABLE documento(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento_versao_id BIGINT NOT NULL,
    documento_origem_id BIGINT,
    paciente_id BIGINT NOT NULL,
    observacao TEXT,
    dados JSONB,
    ativo BOOLEAN,
    usuario_id BIGINT,
    dt_criacao TIMESTAMP,
    dt_atualizacao TIMESTAMP,
    dt_assinatura TIMESTAMP,
    dt_desativado TIMESTAMP,

    CONSTRAINT fk_documento_tipo_documento_versao FOREIGN KEY (tipo_documento_versao_id) REFERENCES tipo_documento_versao(id),
    CONSTRAINT fk_documento_origem FOREIGN KEY (documento_origem_id) REFERENCES documento(id),
    CONSTRAINT fk_documento_paciente FOREIGN KEY (paciente_id) REFERENCES paciente(id),
    CONSTRAINT fk_documento_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);

CREATE TABLE hist_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id BIGINT,
    paciente_id BIGINT,
    acao VARCHAR(200),
    observacao TEXT,
    dt_criacao TIMESTAMP,
    usuario_id BIGINT,

    CONSTRAINT fk_hist_documento_documento FOREIGN KEY (documento_id) REFERENCES documento(id),
    CONSTRAINT fk_hist_documento_paciente FOREIGN KEY (paciente_id) REFERENCES paciente(id),
    CONSTRAINT fk_hist_documento_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);

