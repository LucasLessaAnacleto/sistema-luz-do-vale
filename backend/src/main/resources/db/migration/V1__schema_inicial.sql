CREATE TABLE perfil (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    perm_cad_paciente BOOLEAN DEFAULT FALSE
);

CREATE TABLE profissional (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    telefone VARCHAR(40),
    reg_profissional VARCHAR(255),
    cpf VARCHAR(40),
    endereco_rua VARCHAR(255),
    endereco_nr VARCHAR(40),
    endereco_bairro VARCHAR(255),
    endereco_municipio VARCHAR(255),
    endereco_estado VARCHAR(255),
    dt_nasc DATE
);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    perfil_id BIGINT,
    profissional_id BIGINT UNIQUE,
    role VARCHAR(40),
    ativo BOOLEAN DEFAULT TRUE,
    dt_desativado TIMESTAMP,
    dt_criacao TIMESTAMP,

    CONSTRAINT fk_usuario_perfil FOREIGN KEY (perfil_id) REFERENCES perfil(id),
    CONSTRAINT fk_usuario_profissional FOREIGN KEY (profissional_id) REFERENCES profissional(id)
);

CREATE TABLE token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(255),
    usuario_id BIGINT,

    CONSTRAINT fk_token_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);